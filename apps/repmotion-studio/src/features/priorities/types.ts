/**
 * Module 1: Priorities (The Daily Action Queue) - Domain Types
 * Strongly typed contracts for the Sales Representative morning action queue.
 */

export type PriorityUrgency = "today" | "this_week" | "upcoming";

export type PriorityCategory =
  | "meeting_prep"       // Upcoming customer meeting today
  | "quote_unblocked"    // Stalled quote with newly restocked inventory
  | "service_hold"       // Active customer care escalation (outreach paused)
  | "reorder_cadence"    // Repeat purchasing window due
  | "promise_due"        // Customer commitment due today
  | "churn_risk";        // Unexpected drop in ordering cadence

export type PriorityReadiness = "ready" | "review" | "blocked";

export interface PriorityContact {
  name: string;
  role: string;
  phone: string;
  email: string;
  avatarInitials: string;
}

export interface PriorityAction {
  type: "open_brief" | "release_quote" | "inspect_service" | "log_call" | "fulfill_promise";
  label: string;
  primary?: boolean;
}

export interface PriorityItem {
  id: string;
  accountId: string;
  accountName: string;
  accountTier: "Enterprise" | "Strategic" | "Core";
  annualSpend: string;
  
  // Categorization & Urgency
  category: PriorityCategory;
  categoryLabel: string;
  urgency: PriorityUrgency;
  urgencyLabel: string;
  readiness: PriorityReadiness;
  
  // High-level Title & Story
  title: string;
  description: string;
  potentialValue: string;
  
  // Evidence generated by the foundation
  evidence: string[];
  
  // Primary Contact at Account
  primaryContact: PriorityContact;
  
  // Specific contextual payloads
  meetingDetails?: {
    time: string;
    agenda: string[];
    location: string;
  };
  
  unblockedQuote?: {
    quoteNumber: string;
    totalAmount: number;
    discountPct: number;
    validUntil: string;
    unblockedItems: Array<{
      sku: string;
      name: string;
      quantity: number;
      branchLocation: string;
      stockAvailable: number;
      unitPrice: number;
    }>;
  };
  
  serviceEscalation?: {
    caseNumber: string;
    assignedSpecialist: string;
    priority: "Urgent" | "High" | "Medium";
    status: string;
    subject: string;
    openedAt: string;
    resolutionNote: string;
    blocksPromotionalOutreach: boolean;
    policyMessage: string;
  };

  completed?: boolean;
  completedAt?: string;

  promiseContext?: {
    promiseTitle: string;
    dueTime: string;
    dependency: string;
  };

  reorderCadence?: {
    typicalCycleDays: number;
    daysSinceLastOrder: number;
    leadTimeDays: number;
    typicalOrderValue: string;
  };
}

export interface PriorityFilterState {
  searchQuery: string;
  urgencyFilter: "all" | PriorityUrgency;
  categoryFilter: "all" | PriorityCategory;
  readinessFilter: "all" | PriorityReadiness;
  statusFilter: "active" | "completed" | "all";
}
